#include<stdio.h>

int main()
{
  int a,b;
   printf("Enter the two numbers\n");
   scanf("%d%d",&a,&b);

 printf("Addition:      %d+%d=%d\n",a,b,a+b);
 printf("Substraction:  %d-%d=%d\n",a,b,a-b);
 printf("Multiplication:%d*%d=%d\n",a,b,a*b);
 printf("Division:      %d/%d=%d\n",a,b,a/b);
 printf("Modulus :      %d%%%d=%d\n",a,b,a%b);
 return 0;
}
  
